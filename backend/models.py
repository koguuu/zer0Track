"""zer0track backend data contract — provisional until team's schema.md is locked.

The proposal requires PASS/FAIL/UNKNOWN and role outline mentions `passed` and
`confidence`. `passed` is tri-state to preserve UNKNOWN, while `confidence` is
optional and intentionally never generated by the backend.
"""
from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid", validate_assignment=True)


class Status(str, Enum):
    PASS = "PASS"
    FAIL = "FAIL"
    UNKNOWN = "UNKNOWN"


class LocationEvidence(StrictModel):
    latitude: float = Field(ge=-90, le=90)
    longitude: float = Field(ge=-180, le=180)
    accuracy_m: float = Field(ge=0)
    source: Literal["device_gps", "network", "unknown", "synthetic"]
    recorded_at: datetime
    mock_location_flag: bool = False


class ApprovedCheckpoint(StrictModel):
    checkpoint_id: str
    handoff_type: Literal["doorstep", "guardhouse", "depot", "warehouse"]
    latitude: float = Field(ge=-90, le=90)
    longitude: float = Field(ge=-180, le=180)
    radius_m: float = Field(gt=0)


class ShipmentEvent(StrictModel):
    shipment_id: str = Field(min_length=1)
    parcel_id: str = Field(min_length=1)
    event_id: str = Field(min_length=1)
    transaction_id: str = Field(min_length=1)
    handoff_type: Literal["doorstep", "guardhouse", "depot", "warehouse"]
    event_timestamp: datetime
    receipt_timestamp: datetime
    handler_id: str = Field(min_length=1)  # claimed, never authenticated by itself
    receiver_id: str = Field(min_length=1)  # claimed, checked against trusted records
    transfer_code_ref: str = Field(min_length=1)  # NOT raw OTP/TAC secret
    location: LocationEvidence | None = None
    notes: str | None = Field(default=None, max_length=2000)  # untrusted text
    photo_metadata_ref: str | None = None  # supporting context, NOT authenticated
    signed_receipt_status: Literal["present_unverified", "absent"] | None = None


class CourierHistory(StrictModel):
    courier_id: str
    recent_delivery_count: int = Field(ge=0)
    recent_review_count: int = Field(ge=0)
    observation_window_days: int = Field(ge=1)
    # Context only: history NEVER overrides the three mandatory checks.


class TrustedShipmentRecord(StrictModel):
    shipment_id: str
    parcel_id: str
    assigned_handler_id: str
    current_custodian_id: str
    authorized_receiver_ids: list[str]
    authorized_delegate_ids: list[str] = Field(default_factory=list)
    checkpoints: list[ApprovedCheckpoint]
    custody_state: Literal["PENDING", "ACCEPTED"] = "PENDING"


class TransferCodeRecord(StrictModel):
    code_ref: str
    shipment_id: str
    transaction_id: str
    receiver_id: str
    issued_at: datetime
    expires_at: datetime
    consumed_at: datetime | None = None


class CheckerResult(StrictModel):
    checker_name: Literal["parcel_code_integrity", "identity_authority", "location"]
    status: Status
    passed: bool | None = None
    confidence: float | None = Field(default=None, ge=0, le=1)  # legacy shape only
    detail: str
    evidence_ids: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def sync_passed(self):
        expected = {Status.PASS: True, Status.FAIL: False, Status.UNKNOWN: None}[self.status]
        if self.passed is not None and self.passed != expected:
            raise ValueError("passed contradicts status")
        object.__setattr__(self, "passed", expected)
        return self


class AgentDecision(StrictModel):
    # Named AgentDecision to match role outline; produced by deterministic policy.
    decision: Literal["ACCEPT_READY", "REQUEST_VERIFICATION", "RECOMMEND_HOLD", "ESCALATE"]
    recommended_action: str
    requires_human_approval: bool
    reason: str
    unresolved_checks: list[str] = Field(default_factory=list)
    evidence_ids: list[str] = Field(default_factory=list)


class ApprovalRequest(StrictModel):
    action: Literal["accept", "hold", "reject", "escalate"]
    expected_case_version: int = Field(ge=1)
    reason: str = Field(min_length=3, max_length=1000)
    approval_request_id: str = Field(min_length=1)


class ApprovalRecord(StrictModel):
    approval_id: str
    shipment_id: str
    evidence_version: int = Field(ge=1)
    operator_id: str
    action: Literal["accept", "hold", "reject", "escalate"]
    reason: str
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class CaseView(StrictModel):
    shipment_id: str
    version: int
    state: str
    event: ShipmentEvent
    checks: list[CheckerResult]
    decision: AgentDecision
    approval: ApprovalRecord | None = None
